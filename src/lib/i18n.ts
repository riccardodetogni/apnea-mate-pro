export type Language = "it" | "en";

let currentLanguage: Language = "it";

export const setLanguage = (lang: Language) => {
  currentLanguage = lang;
  localStorage.setItem("apnea-mate-lang", lang);
};

export const getLanguage = (): Language => {
  const stored = typeof localStorage !== "undefined"
    ? (localStorage.getItem("apnea-mate-lang") as Language | null)
    : null;
  if (stored && (stored === "it" || stored === "en")) {
    currentLanguage = stored;
    return currentLanguage;
  }
  if (typeof navigator !== "undefined" && navigator.language) {
    currentLanguage = navigator.language.toLowerCase().startsWith("it") ? "it" : "en";
  }
  return currentLanguage;
};

export const getLocale = (): string => (getLanguage() === "en" ? "en-GB" : "it-IT");

export const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
  const raw = (translations[currentLanguage] as any)[key] || (translations.it as any)[key] || key;
  if (typeof raw !== "string") return String(raw);
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
};

export const useTranslation = () => {
  return { t, language: currentLanguage, setLanguage, getLanguage };
};

